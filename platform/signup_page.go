// signup_page.go renders the three browser pages of the web-signup flow. They are built by
// concatenation rather than html/template because everything interpolated is either ours or
// has been through sanitizeForHTML — and a template would hide that fact rather than make it
// checkable. Every call site below passes a sanitized value.

